/** `?` → `$1, $2, …` (в наших запросах нет вопросительных знаков внутри строк). */
export function toPositional(sql) {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

/** Единый интерфейс поверх pg.Pool / pg.Client / PGlite: all, get, run, tx. */
function adapter(executor, { inTx = false, begin } = {}) {
  const send = async (sql, params = []) => (await executor.query(toPositional(sql), params)).rows;
  // Транзакция — одно соединение: параллельные запросы (Promise.all) ставим в очередь, пул же раздаёт их сам.
  let chain = Promise.resolve();
  const query = inTx
    ? (sql, params) => { const run = chain.then(() => send(sql, params)); chain = run.catch(() => {}); return run; }
    : send;
  const db = {
    all: query,
    get: async (sql, params) => (await query(sql, params))[0],
    run: query,
    /** Атомарно выполняет fn(txDb). Внутри транзакции вложенный tx просто выполняет fn. */
    tx: (fn) => (inTx ? fn(db) : begin(fn)),
  };
  return db;
}

/** runScript выполняет многооператорный SQL (pg — простой запрос без параметров, PGlite — exec). */
async function migrate(executor, runScript = (sql) => executor.query(sql)) {
  await executor.query('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY)');
  const { rows } = await executor.query('SELECT COALESCE(MAX(version), 0) AS v FROM schema_migrations');
  for (let v = Number(rows[0].v); v < MIGRATIONS.length; v += 1) {
    await executor.query('BEGIN');
    try {
      await runScript(MIGRATIONS[v]);
      await executor.query('INSERT INTO schema_migrations (version) VALUES ($1)', [v + 1]);
      await executor.query('COMMIT');
    } catch (err) {
      await executor.query('ROLLBACK');
      throw err;
    }
  }
}

/** sslmode=require в pg скоро сменит смысл — явно просим полную проверку сертификата (у Neon он валидный). */
const strictSsl = (url) => url.replace(/([?&])sslmode=(require|prefer|verify-ca)(?=&|$)/, '$1sslmode=verify-full');

/**
 * Подключение к Neon: пул для приложения (pooled DATABASE_URL), миграции — по прямому адресу.
 * @param {{ url: string, migrationUrl?: string }} options
 */
export async function openDb({ url, migrationUrl = url }) {
  if (!url) throw new Error('DATABASE_URL не задан — выполните `neon env pull` или впишите строку подключения в .env');
  const direct = new pg.Client({ connectionString: strictSsl(migrationUrl) });
  await direct.connect();
  try {
    await direct.query('SELECT pg_advisory_lock(727001)'); // два сервера не мигрируют одновременно
    await migrate(direct);
  } finally {
    await direct.end();
  }

  const pool = new pg.Pool({ connectionString: strictSsl(url), max: 10, idleTimeoutMillis: 30_000 });
  const begin = async (fn) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await fn(adapter(client, { inTx: true }));
      await client.query('COMMIT');
      return result;
    } catch (err) {
      await client.query('ROLLBACK').catch(() => {});
      throw err;
    } finally {
      client.release();
    }
  };
  return { ...adapter(pool, { begin }), pool, close: () => pool.end() };
}

/** Postgres в памяти процесса (PGlite) — для тестов и демо без сети. */
export async function openMemoryDb() {
  const { PGlite } = await import('@electric-sql/pglite');
  const lite = new PGlite();
  await migrate(lite, (sql) => lite.exec(sql));
  let queue = Promise.resolve(); // PGlite — одно соединение: транзакции выполняем по очереди
  const begin = (fn) => {
    const run = queue.then(() => lite.transaction((t) => fn(adapter(t, { inTx: true }))));
    queue = run.catch(() => {});
    return run;
  };
  return { ...adapter(lite, { begin }), close: () => lite.close() };
}
