// Классический скрипт в <head>: включает «режим со скриптами» до первой отрисовки
// (прелоадер hero и отложенный старт анимаций). Если основной скрипт не загрузился,
// через 12 секунд страница возвращается в обычный вид и ничего не остаётся «под шторкой».
document.documentElement.classList.add('js');
setTimeout(() => document.documentElement.classList.remove('js'), 12000);
